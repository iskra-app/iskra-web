/**
 * Жест кнопки записи — как в нативной Искре, и одинаковый для пальца и мыши:
 *
 * - **зажал → говоришь → отпустил** — отправилось;
 * - **увёл в сторону** (к «Отмене») — выброшено;
 * - **увёл вверх** — запись идёт дальше без рук, отправка — кнопкой;
 * - **короткое нажатие** — тоже без рук. На десктопе это главный путь (см. план, «Кодеки»):
 *   держать кнопку мыши минуту — не жест, а упражнение. Клик начинает, «Отправить» или
 *   «Остановить» заканчивают.
 *
 * Пороги — в CSS px от точки нажатия. Влево — в письме слева направо; в другую сторону
 * отменяет так же: «Отмена» в полосе — по ту сторону от кнопки, куда бы ни шло письмо.
 */

/** Короче — это нажатие, а не удержание. */
export const HOLD_MS = 300;
/** Столько в сторону — отмена. */
export const CANCEL_PX = 96;
/** Столько вверх — без рук. */
export const LOCK_PX = 64;

export type RecordMove = 'hold' | 'cancel' | 'lock';

/** Куда увели палец, пока держит. Вверх важнее: замок ловит чуть кривое движение вверх. */
export function moveOf(dx: number, dy: number): RecordMove {
  if (-dy >= LOCK_PX && -dy > Math.abs(dx)) return 'lock';
  if (Math.abs(dx) >= CANCEL_PX && Math.abs(dx) > -dy) return 'cancel';
  return 'hold';
}

/** Отпустили: долгое удержание отправляет, короткое нажатие оставляет запись без рук. */
export function releaseOf(heldMs: number): 'send' | 'handsFree' {
  return heldMs >= HOLD_MS ? 'send' : 'handsFree';
}
